#!/usr/bin/env python3
"""Build an ESP32 compose benchmark from the firmware UI sources and run it in Espressif QEMU.

usage: make_bench.py <fw_dir> <out_dir> [--old]
The sketch renders every profiled screen into a RAM band buffer (no display, no Wi-Fi),
exactly like host_prof.cpp, and prints the per-layer times. QEMU runs with -icount 0
(1 instruction = 1 ns of virtual time), so the reported "us" are thousands of instructions.
"""
import os, shutil, subprocess, sys, re
fw, out = sys.argv[1], sys.argv[2]
old = '--old' in sys.argv
HOST = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sk = os.path.join(out, 'AURA_bench')
shutil.rmtree(out, ignore_errors=True)
os.makedirs(sk)
UI = ['gfx.cpp', 'assets.cpp', 'ui_core.cpp', 'boot_screen.cpp', 'home_screen.cpp', 'menu_screen.cpp', 'buddy_face.cpp',
      'apps_wx.cpp', 'apps_data.cpp', 'apps_tools.cpp', 'settings_screen.cpp', 'prof.cpp', 'aurora_fx.cpp']
for f in os.listdir(fw):
    p = os.path.join(fw, f)
    if f.endswith('.h') and f != 'build_opt.h': shutil.copy(p, sk)
for f in UI:
    p = os.path.join(fw, f)
    if os.path.exists(p): shutil.copy(p, sk)
shutil.copytree(os.path.join(fw, 'src'), os.path.join(sk, 'src'))
if not os.path.exists(os.path.join(fw, 'prof.h')):  # v3.1.0: no profiler, totals only
    for f in ('prof.h', 'prof.cpp'): shutil.copy(os.path.join(HOST, '..', 'fw', 'AURA_v3', f), sk)
open(os.path.join(sk, 'build_opt.h'), 'w').write('-DAURA_HOST -DAURA_BENCH\n')
# prof: esp_timer on the bench
pc = open(os.path.join(sk, 'prof.cpp')).read().replace('#ifdef AURA_HOST', '#if defined(AURA_HOST) && !defined(AURA_BENCH)')
open(os.path.join(sk, 'prof.cpp'), 'w').write(pc)
shutil.copy(os.path.join(HOST, 'host_hal.cpp'), os.path.join(sk, 'bench_hal.cpp'))
hm = open(os.path.join(HOST, 'host_main.cpp')).read()
hm = hm.replace('static uint16_t s_fb[320 * 240];', '')
hm = re.sub(r'    for \(int i = 0; i < 320 \* 20; i\+\+\) \{\n.*?\n.*?\n    \}\n', '', hm, flags=re.S)
hm = hm[:hm.index('void host_save(')] + hm[hm.index('static void sample_data(void)'):]
hm = hm[:hm.index('int host_prof_main(int argc, char **argv);')]
hm += '\nvoid bench_init(void) { sample_data(); ui_init(1000); }\n'
open(os.path.join(sk, 'bench_main.cpp'), 'w').write(hm)
hp = open(os.path.join(HOST, 'host_prof.cpp')).read()
open(os.path.join(sk, 'bench_prof.cpp'), 'w').write(hp)
open(os.path.join(sk, 'AURA_bench.ino'), 'w').write('''// generated by make_bench.py
#include <Arduino.h>
void bench_init(void);
int host_prof_main(int argc, char **argv);
void setup() {
  Serial.begin(115200);
  delay(50);
  printf("[bench] start heap=%lu\\n", (unsigned long)ESP.getFreeHeap());
  bench_init();
  static char a0[] = "bench", a1[] = "--prof", a2[] = "20";
  char *av[] = {a0, a1, a2};
  host_prof_main(3, av);
  printf("[bench] done\\n");
}
void loop() { delay(1000); }
''')
print(sk)
